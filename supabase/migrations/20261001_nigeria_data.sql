  ))::integer AS quantity,
  per.start_date AS period_start,
  per.end_date AS period_end,
  (per.end_date + interval '1 day')::timestamptz AS recorded_at
FROM facility_medicine_pairs p
CROSS JOIN periods per
ON CONFLICT (id) DO NOTHING;


-- PART B: INVENTORY
INSERT INTO public.inventory (id, facility_id, medicine_id, quantity, batch_number, expiry_date, recorded_at)
WITH avg_consumption AS (
  SELECT
    c.facility_id,
    c.medicine_id,
    AVG(c.quantity)::numeric AS avg_qty,
    (RIGHT(c.facility_id::text, 4))::integer AS fac_num,
    (RIGHT(c.medicine_id::text, 4))::integer AS med_num
  FROM public.consumption c
  WHERE c.facility_id >= '00000000-0000-0000-0000-000000000701'
    AND c.facility_id <= '00000000-0000-0000-0000-000000000760'
  GROUP BY c.facility_id, c.medicine_id
)
SELECT
  md5('inventory:ng:' || a.facility_id || ':' || a.medicine_id)::uuid AS id,
  a.facility_id,
  a.medicine_id,
  GREATEST(5, ROUND(
    a.avg_qty * (0.55 + 1.1 * abs(sin(a.fac_num * 29.3 + a.med_num * 13.1)))
  ))::integer AS quantity,
  'LOT-NG-2026-' || LPAD((((a.fac_num * 31 + a.med_num * 17) % 899) + 100)::text, 3, '0') AS batch_number,
  (CURRENT_DATE + INTERVAL '8 months' + (((a.fac_num * 23 + a.med_num * 11) % 400) * INTERVAL '1 day'))::date AS expiry_date,
  NOW() AS recorded_at
FROM avg_consumption a
ON CONFLICT (id) DO NOTHING;


