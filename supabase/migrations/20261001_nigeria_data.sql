  p.facility_id,
  p.medicine_id,
  GREATEST(1, ROUND(
    p.base_demand * p.scale_factor
    * (CASE
        WHEN p.med_num IN (101, 102, 103) AND per.month_idx IN (1, 2) THEN 1.45
        WHEN p.med_num IN (101, 102, 103) AND per.month_idx IN (5, 6) THEN 0.65
        ELSE 1.00
